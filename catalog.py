# 식자재 → 대분류 역인덱스 (get_category 에서 사용)
_INGREDIENT_TO_CATEGORY: dict[str, str] = {
    ingredient: category for category, items in CATALOG.items() for ingredient in items
}


def _validate_catalog() -> None:
    """카탈로그 데이터의 일관성을 확인한다 (모듈 로드 시 1회 실행).

    Raises:
        ValueError: 식자재 이름이 여러 대분류에 중복될 때.
    """
    all_items = [ingredient for items in CATALOG.values() for ingredient in items]
    duplicates = {name for name in all_items if all_items.count(name) > 1}
    if duplicates:
        raise ValueError(f"식자재 이름이 여러 대분류에 중복됨: {sorted(duplicates)}")


_validate_catalog()


def list_categories() -> list[str]:
    """대분류 목록을 화면 표시 순서대로 반환한다."""
    return list(CATALOG.keys())


def list_ingredients(category: str) -> list[str]:
    """대분류에 속한 식자재 목록을 반환한다.

    Raises:
        KeyError: 카탈로그에 없는 대분류일 때.
    """
    return list(CATALOG[category])


def get_category(ingredient: str) -> str | None:
    """식자재가 속한 대분류를 반환한다. 카탈로그에 없으면 None."""
    return _INGREDIENT_TO_CATEGORY.get(ingredient)


def main() -> None:
    """단독 실행 데모: 카탈로그 전체를 출력한다."""
    for category in list_categories():
        items = list_ingredients(category)
        print(f"[{category}] ({len(items)}개) {', '.join(items)}")
    print(f"--- 대분류 {len(CATALOG)}개 / 식자재 {len(_INGREDIENT_TO_CATEGORY)}개")

    for name in ["양파", "트러플"]:
        print(f"get_category({name!r}) -> {get_category(name)!r}")


if __name__ == "__main__":
    main()
